/**
 * Check if an email domain is a known disposable/temporary email service
 * @param email The email address to check
 * @returns true if the domain is disposable, false otherwise
 */
export function isDisposableEmail(email: string): boolean {
  if (!email || typeof email !== 'string') {
    return false;
  }

  // Extract domain from email
  const emailParts = email.toLowerCase().split('@');
  if (emailParts.length !== 2) {
    return false;
  }

  const domain = emailParts[1].trim();
  
  // Check against known disposable domains
  return DISPOSABLE_EMAIL_DOMAINS.has(domain);
}

/**
 * Get the domain from an email address
 * @param email The email address
 * @returns The domain part of the email, or empty string if invalid
 */
export function getEmailDomain(email: string): string {
  if (!email || typeof email !== 'string') {
    return '';
  }

  const emailParts = email.toLowerCase().split('@');
  if (emailParts.length !== 2) {
    return '';
  }

  return emailParts[1].trim();
}

/**
 * Get a user-friendly error message for disposable email
 * @param email The disposable email address
 * @returns Localized error message
 */
export function getDisposableEmailError(email: string): string {
  const domain = getEmailDomain(email);
  return `Email dari ${domain} tidak diizinkan. Silakan gunakan email permanen untuk pendaftaran.`;
}